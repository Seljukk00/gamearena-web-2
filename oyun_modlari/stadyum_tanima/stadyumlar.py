def normalize_answer(text):
    """Cevap normalleştirme"""
    if not text:
        return ""
    import unicodedata
    text = text.lower().strip()
    text = text.replace("ı", "i").replace("ğ", "g").replace("ü", "u")
    text = text.replace("ş", "s").replace("ö", "o").replace("ç", "c")
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode("ascii")
    # Fazla bosluklari sil
    text = " ".join(text.split())
    return text


def check_answer(stadyum, user_answer):
    """Cevap dogru mu kontrol et"""
    if not user_answer:
        return False
    
    normalized = normalize_answer(user_answer)
    
    # Ana isim
    if normalize_answer(stadyum["isim"]) == normalized:
        return True
    
    # Alternatif isimler
    for alt in stadyum.get("alternatif_isimler", []):
        if normalize_answer(alt) == normalized:
            return True
    
    # Kismi eslesme (ana ismin bir parcasi)
    main_words = normalize_answer(stadyum["isim"]).split()
    user_words = normalized.split()
    if len(user_words) >= 2 and all(w in main_words for w in user_words):
        return True
    
    return False